#!/usr/bin/env python3
"""Step 6: route statistics -> stdout + docs/route/stats.md, docs/route/profile.png, docs/route/topdown.png.

Bend definition: a maximal run of samples with |curv| > 1/150 m^-1 and the same sign; runs of the same sign
separated by <= 12 m of straighter road (|curv| <= 1/150) are merged. Bend angle = |integral of curv ds| over
the merged run (including the merged gaps). Position = s of the bend's peak |curv|."""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import BUILT, DOCS

KT = 1 / 150.0
GAP = 12.0


def read_meta():
    m = {}
    for line in open(os.path.join(BUILT, 'meta.txt')):
        k, *v = line.split()
        m[k] = v
    return m


def bends(s, k):
    sign = np.where(np.abs(k) > KT, np.sign(k), 0)
    runs = []
    i = 0
    while i < len(s):
        if sign[i] == 0:
            i += 1; continue
        j = i
        while j + 1 < len(s) and sign[j + 1] == sign[i]:
            j += 1
        runs.append([i, j, sign[i]])
        i = j + 1
    merged = []
    for r in runs:
        if merged and merged[-1][2] == r[2] and s[r[0]] - s[merged[-1][1]] <= GAP:
            merged[-1][1] = r[1]
        else:
            merged.append(r)
    out = []
    for a, b, sg in merged:
        ang = abs(np.trapezoid(k[a:b + 1], s[a:b + 1])) if b > a else abs(k[a]) * (s[1] - s[0])
        pk = a + int(np.argmax(np.abs(k[a:b + 1])))
        out.append(dict(s0=s[a], s1=s[b], s=s[pk], deg=np.degrees(ang), dir='L' if sg > 0 else 'R',
                        rmin=1 / abs(k[pk])))
    return out


def steepest(s, z, win):
    ds = s[1] - s[0]
    n = int(round(win / ds))
    g = (z[n:] - z[:-n]) / (s[n:] - s[:-n])
    iu, idn = int(np.argmax(g)), int(np.argmin(g))
    return g[iu] * 100, s[iu], g[idn] * 100, s[idn]


def main():
    d = np.loadtxt(os.path.join(BUILT, 'route.csv'), delimiter=',', skiprows=1)
    s, x, y, z, zd, hd, k = d.T
    meta = read_meta()
    L = s[-1]
    dz = np.diff(z)
    climb, desc = dz[dz > 0].sum(), -dz[dz < 0].sum()
    up, su, dn, sd = steepest(s, z, 100.0)
    # project-file comparison: raw DEM at 20 m sampling
    s20 = np.arange(0, L, 20.0); z20 = np.interp(s20, s, zd)
    up20, su20, dn20, sd20 = steepest(s20, z20, 100.0)
    dz20 = np.diff(z20)
    B = bends(s, k)
    b60 = [b for b in B if b['deg'] >= 60]; b90 = [b for b in B if b['deg'] >= 90]
    b30 = [b for b in B if b['deg'] >= 30]
    big = max(B, key=lambda b: b['deg'])
    imin = int(np.argmax(np.abs(k)))
    ford_s = float(meta['ford_s'][0]); b0 = float(meta['bridge_s0'][0])
    zf = np.interp(ford_s, s, z)
    after = (s > ford_s) & (s < b0)
    peak_after = z[after].max(); s_peak_after = s[after][np.argmax(z[after])]
    plat = (s > 400) & (s < 3500)

    lines = []
    P = lines.append
    P('# Bush Drift route stats (hut -> bridge)\n')
    P('Generated by `scripts/route_stats.py` from `data/built/route.csv` (2 m samples of the imagery-refined centreline, '
      'smoothed road elevation from the NSW 5 m DEM).\n')
    P('| | This build | Project file (OSM line, 20 m DEM samples) |')
    P('|---|---|---|')
    P(f'| Length | {L / 1000:.2f} km | 7.80 km |')
    P(f'| Total climb / descent (smoothed elev) | +{climb:.0f} m / -{desc:.0f} m | ~145 m / ~400 m |')
    P(f'| Total climb / descent (raw DEM @ 20 m) | +{dz20[dz20 > 0].sum():.0f} m / -{-dz20[dz20 < 0].sum():.0f} m | |')
    P(f'| Steepest 100 m up (smoothed) | +{up:.1f} % at km {su / 1000:.2f} | +18 % |')
    P(f'| Steepest 100 m down (smoothed) | {dn:.1f} % at km {sd / 1000:.2f} | -21 % |')
    P(f'| Steepest 100 m up / down (raw DEM @ 20 m) | +{up20:.1f} % at km {su20 / 1000:.2f} / {dn20:.1f} % at km {sd20 / 1000:.2f} | +18 % / -21 % |')
    P(f'| Bends >= 30 deg | {len(b30)} | 42 |')
    P(f'| Bends >= 60 deg | {len(b60)} | 17 |')
    P(f'| Bends >= 90 deg | {len(b90)} | 7 |')
    P(f'| Biggest bend | {big["deg"]:.0f} deg {big["dir"]} at km {big["s"] / 1000:.2f} | ~156 deg at km 6.2 |')
    P(f'| Min radius (centreline) | {1 / abs(k[imin]):.1f} m at km {s[imin] / 1000:.2f} | |')
    P(f'| Elevations | start {z[0]:.0f} m, plateau {z[plat].min():.0f}-{z[plat].max():.0f} m (km 0.4-3.5), '
      f'ford {zf:.0f} m at km {ford_s / 1000:.2f}, then up to {peak_after:.0f} m at km {s_peak_after / 1000:.2f}, '
      f'bridge {z[-1]:.0f} m | hut 918, plateau 930-949, ford 675 at km 5.84, ~721, bridge 663 |')
    P('')
    P(f'Bend definition: maximal run with |curvature| > 1/150 m^-1 and constant sign, same-sign runs merged across '
      f'gaps <= {GAP:.0f} m; angle = |integral curv ds| over the run. Steepest 100 m = max/min of (z(s+100)-z(s))/100.\n')
    P('## Bends >= 60 deg\n')
    P('| km | angle | dir | min radius | extent (km) |')
    P('|---|---|---|---|---|')
    for b in b60:
        P(f'| {b["s"] / 1000:.2f} | {b["deg"]:.0f} deg{" **(>=90)**" if b["deg"] >= 90 else ""} | {b["dir"]} | '
          f'{b["rmin"]:.0f} m | {b["s0"] / 1000:.2f}-{b["s1"] / 1000:.2f} |')
    P('')
    P('## Notes\n')
    P(f'- Ford position: the OSM ford node (4417047980) sits at km {ford_s / 1000:.2f} on this line (and at km 6.65 on the '
      f'raw OSM join), not km 5.84 as the project file says; the DEM dip (~{zf:.0f} m) confirms it. The 5.84 figure '
      'looks like a measurement slip in the earlier pass.')
    P('- The minimum radius is set by a kink limiter in build_route.py (R >= 10 m): the OSM line is coarse and its '
      'node corners (the Robinsons/Cattlemens junction, the ford V) would otherwise give radii of 2-5 m.')
    P('- Elevation: DEM is photogrammetric (stereo imagery); under dense canopy it is smoother/less reliable. '
      'Smoothed road profile = 9 m median + Gaussian sigma 15 m (5 m near the ford).')
    open(os.path.join(DOCS, 'stats.md'), 'w').write('\n'.join(lines) + '\n')
    print('\n'.join(lines))
    plots(s, x, y, z, zd, k, B, ford_s, b0, meta)


def plots(s, x, y, z, zd, k, B, ford_s, b0, meta):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    ink, muted, grid, blue, raw = '#1f1f1d', '#6b6b66', '#e4e3df', '#2a78d6', '#a9a8a3'
    plt.rcParams.update({'font.size': 9, 'axes.edgecolor': muted, 'axes.labelcolor': ink, 'xtick.color': muted,
                         'ytick.color': muted, 'axes.spines.top': False, 'axes.spines.right': False})
    fig, ax = plt.subplots(figsize=(11, 3.8), dpi=130)
    ax.plot(s / 1000, zd, color=raw, lw=0.8, label='raw DEM at the centreline')
    ax.plot(s / 1000, z, color=blue, lw=2, label='smoothed road surface (elev)')
    ax.grid(True, color=grid, lw=0.6); ax.set_axisbelow(True)
    zf = np.interp(ford_s, s, z)
    for sx, zz, t in ((0, z[0], 'Alexanders Hut'), (ford_s, zf, 'Solomons Creek ford'), (s[-1], z[-1], 'Tantawangalo Ck bridge')):
        ax.plot([sx / 1000], [zz], 'o', ms=6, color=ink, mec='white', mew=1.5)
        ax.annotate(f'{t}\n{zz:.0f} m', (sx / 1000, zz), xytext=(0, -26 if t != 'Alexanders Hut' else 10),
                    textcoords='offset points', ha='center' if 0 < sx < s[-1] else ('left' if sx == 0 else 'right'),
                    fontsize=8, color=ink)
    ax.set_xlabel('distance from hut (km)'); ax.set_ylabel('elevation (m)')
    ax.set_title('Elevation profile, hut to bridge (NSW 5 m DEM)', loc='left', color=ink, fontsize=11)
    ax.set_xlim(0, s[-1] / 1000); ax.legend(frameon=False, loc='lower left')
    fig.tight_layout(); fig.savefig(os.path.join(DOCS, 'profile.png')); plt.close(fig)

    fig, ax = plt.subplots(figsize=(10, 6.2), dpi=130)
    ax.plot(x, y, color=blue, lw=2)
    ax.set_aspect('equal'); ax.grid(True, color=grid, lw=0.6); ax.set_axisbelow(True)
    for km in range(1, int(s[-1] / 1000) + 1):
        i = int(np.argmin(abs(s - km * 1000)))
        ax.plot(x[i], y[i], 'o', ms=4, color=ink); ax.annotate(f'{km} km', (x[i], y[i]), xytext=(5, 4),
                                                                textcoords='offset points', fontsize=7, color=muted)
    for b in B:
        if b['deg'] >= 90:
            i = int(np.argmin(abs(s - b['s'])))
            ax.plot(x[i], y[i], 'o', ms=9, mfc='none', mec=ink, mew=1)
            ax.annotate(f'{b["deg"]:.0f}°', (x[i], y[i]), xytext=(7, -10), textcoords='offset points', fontsize=7, color=ink)
    i = int(np.argmin(abs(s - ford_s)))
    ax.annotate('ford', (x[i], y[i]), xytext=(-10, 12), textcoords='offset points', fontsize=8, color=ink)
    ax.plot(0, 0, 's', ms=7, color=ink); ax.annotate('start pad (origin)', (0, 0), xytext=(6, 6), textcoords='offset points', fontsize=8, color=ink)
    ax.annotate('bridge', (x[-1], y[-1]), xytext=(-30, -14), textcoords='offset points', fontsize=8, color=ink)
    ax.set_xlabel('x east (m)'); ax.set_ylabel('y north (m)')
    ax.set_title('Route, top-down (local frame; circles = bends >= 90°)', loc='left', color=ink, fontsize=11)
    fig.tight_layout(); fig.savefig(os.path.join(DOCS, 'topdown.png')); plt.close(fig)


if __name__ == '__main__':
    main()
